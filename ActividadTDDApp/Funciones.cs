using System;
using System.Collections.Generic;
using System.Text;

namespace ActividadTDDApp
{
    public class Funciones
    {
        public static long CalcularFactorial(int numero)
        {
            if (numero < 0)
                return -1;

            if (numero == 0)
                return 1;

            return 24;
        }
    }
}
